import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { chromium } from 'playwright';
import { createApp } from '../../src/web/http.mts';

test('RF-1 to RF-7: dashboard registration, offers, history, failures and mobile layout', async t => {
  const app = createApp({ database: ':memory:', demo: true });
  app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening');
  t.after(() => app.close());
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || undefined });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  const external = []; const errors = [];
  await context.route('**/*', route => {
    if (new URL(route.request().url()).origin === base) return route.continue();
    external.push(route.request().url()); return route.abort();
  });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  assert.equal(await page.locator('html').getAttribute('lang'), 'es');
  await page.getByRole('button', { name: 'Cargar ejemplos' }).click();
  await page.waitForFunction(() => document.querySelector('#count-offers').textContent === '2');
  assert.equal(await page.locator('#products tr').count(), 3);
  await page.getByRole('button', { name: 'Mejores ofertas', exact: true }).click();
  assert.match(await page.locator('#products tr').first().innerText(), /Adidas/);
  await page.locator('.scenario[data-id="1"]').selectOption('sale');
  await page.waitForFunction(() => document.querySelector('#products tr')?.textContent.includes('650,00 BOB'));
  await page.getByRole('button', { name: 'Ver histórico del producto 1', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  assert.match(await page.locator('#history-content').innerText(), /650,00 BOB/);
  assert.equal(await page.locator('#history-content tbody tr').count(), 2);
  assert.match(await page.locator('#history-content').innerText(), /10 BOB/);
  await page.getByRole('button', { name: 'Cerrar histórico' }).click();
  await page.locator('.scenario[data-id="1"]').selectOption('blocked');
  await page.waitForFunction(() => document.querySelector('#count-offers').textContent === '1');
  await page.getByRole('button', { name: /Todos/ }).click();
  assert.match(await page.locator('#products tr[data-id="1"]').innerText(), /Consulta bloqueada/);
  assert.match(await page.locator('#products tr[data-id="1"]').innerText(), /650,00 BOB/);
  await page.getByLabel('Enlace del producto').fill('https://evil.test/shoe');
  await page.getByLabel('Color exacto').fill('Negro');
  await page.getByLabel('Talla en cm', { exact: true }).fill('27');
  await page.getByRole('button', { name: 'Seguir producto' }).click();
  await page.waitForFunction(() => document.querySelector('#form-message').textContent.includes('Solo se admiten'));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('#add-button').isVisible(), true);
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: 'test-results/dashboard.png', fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
});
